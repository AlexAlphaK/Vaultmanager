#!/usr/bin/env python3
"""Bakes the Chinese characters the game uses into art/cjk_glyphs.gd, so PixelFont can draw them.

    pip install fonttools brotli pillow
    python3 locale/make_cjk_glyphs.py

Run it after the Chinese translation changes (update_po.py says when). It takes every
character in the .po files and in the game's scripts that the pixel font lacks, draws it
from Fusion Pixel 8px (locale/fonts, SIL Open Font License, see OFL.txt) and writes
the bitmaps as 7 rows, top row one pixel above the cap line, bottom row on the baseline
row below it. A character the font lacks too is reported and left out.
"""
import io, os, re, sys

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(ROOT, "locale", "fonts", "fusion-pixel-8px-proportional-sc.woff2")
## Characters only the Traditional translations (zh_TW, zh_HK) use come from the
## Traditional cut, which draws them the way Taiwan and Hong Kong write them.
FONT_TC = os.path.join(ROOT, "locale", "fonts", "fusion-pixel-8px-proportional-tc.woff2")
TRADITIONAL = ("zh_TW.po", "zh_HK.po")
OUT = os.path.join(ROOT, "art", "cjk_glyphs.gd")
SKIP_DIRS = (".godot", ".git", "tests", "tools", "store", "price-service", "prototype", "build", "docs")
TOP = 3  # Fusion Pixel's ascent is 9 px: the glyph box starts 3 rows down
ROWS = 7


def pixel_font_chars():
	src = open(os.path.join(ROOT, "art", "pixel_font.gd"), encoding="utf8").read()
	return set(m.group(1) for m in re.finditer(r'^\t"(.|\\\\|\\")": \[', src, re.M)) | {" "}


def used_chars(traditional):
	"""Characters in the scripts and .po files: the Traditional ones, or all the others."""
	chars = set()
	for root, dirs, files in os.walk(ROOT):
		if os.path.relpath(root, ROOT).split(os.sep)[0] in SKIP_DIRS:
			dirs[:] = []
			continue
		for f in files:
			if (f in TRADITIONAL) if traditional else (f.endswith(".po") and f not in TRADITIONAL) or (f.endswith(".gd") and f != "cjk_glyphs.gd"):
				chars |= set(open(os.path.join(root, f), encoding="utf8").read())
	return chars


def load(path):
	otf = TTFont(path)
	otf.flavor = None
	buf = io.BytesIO()
	otf.save(buf)
	return otf.getBestCmap(), ImageFont.truetype(io.BytesIO(buf.getvalue()), 8)


def main():
	have = pixel_font_chars()
	simplified = set(c for c in used_chars(False) if ord(c) >= 0x2000 and c not in have)
	traditional = set(c for c in used_chars(True) if ord(c) >= 0x2000 and c not in have) - simplified
	fonts = {False: load(FONT), True: load(FONT_TC)}
	lines, missing = [], []
	for ch in sorted(simplified | traditional):
		cmap, font = fonts[ch in traditional]
		if ord(ch) not in cmap:
			missing.append(ch)
			continue
		w = int(font.getlength(ch)) - 1
		im = Image.new("1", (w + 2, 14), 0)
		d = ImageDraw.Draw(im)
		d.fontmode = "1"
		d.text((0, 0), ch, font=font, fill=1)
		box = im.getbbox()
		if box and (box[1] < TOP or box[3] > TOP + ROWS):
			print("warning: %s spills out of the 7-row box %s" % (ch, box))
		rows = "".join("%02x" % sum(1 << x for x in range(w) if im.getpixel((x, TOP + y))) for y in range(ROWS))
		key = '"\\""' if ch == '"' else '"%s"' % ch
		lines.append('\t%s: "%d%s",' % (key, w, rows))
	out = [
		"class_name CjkGlyphs",
		"extends RefCounted",
		"## Chinese characters for PixelFont, drawn from Fusion Pixel 8px (SIL Open Font License 1.1,",
		"## see locale/fonts/OFL.txt). Generated by locale/make_cjk_glyphs.py: do not edit by hand.",
		"## Each entry is the width (one digit) then 7 rows as hex bytes, bit 0 the left pixel.",
		"",
		"const ROWS := {",
	] + lines + ["}", ""]
	open(OUT, "w", encoding="utf8").write("\n".join(out))
	print("%d characters written to art/cjk_glyphs.gd" % len(lines))
	if missing:
		print("the font lacks: " + " ".join(missing))
		sys.exit(1)


if __name__ == "__main__":
	main()
